// ── Transport-level abuse ───────────────────────────────────────────────────

#[tokio::test]
async fn abusive_content_headers_are_answered_with_a_sane_status() {
    let router = default_router();
    let game = new_game_bytes().await;
    // The body extractor is byte-oriented, so a wrong or absent media type is
    // allowed to succeed; what it may never do is fail as a server error.
    let sane = [
        StatusCode::OK,
        StatusCode::BAD_REQUEST,
        StatusCode::LENGTH_REQUIRED,
        StatusCode::PAYLOAD_TOO_LARGE,
        StatusCode::UNSUPPORTED_MEDIA_TYPE,
    ];

    let cases: Vec<(&str, Request<Body>)> = vec![
        (
            "bogus content-type",
            Request::builder()
                .method(Method::POST)
                .uri("/moves")
                .header("content-type", "text/html; charset=utf-8")
                .body(Body::from(game.clone()))
                .expect("valid request"),
        ),
        (
            "no content-type",
            Request::builder()
                .method(Method::POST)
                .uri("/moves")
                .body(Body::from(game.clone()))
                .expect("valid request"),
        ),
        (
            "content-length larger than the body",
            Request::builder()
                .method(Method::POST)
                .uri("/moves")
                .header("content-type", "application/octet-stream")
                .header("content-length", "9999")
                .body(Body::from(game.clone()))
                .expect("valid request"),
        ),
        (
            "content-length smaller than the body",
            Request::builder()
                .method(Method::POST)
                .uri("/moves")
                .header("content-type", "application/octet-stream")
                .header("content-length", "2")
                .body(Body::from(game.clone()))
                .expect("valid request"),
        ),
        (
            "content-length that is not a number",
            Request::builder()
                .method(Method::POST)
                .uri("/moves")
                .header("content-type", "application/octet-stream")
                .header("content-length", "not-a-number")
                .body(Body::from(game.clone()))
                .expect("valid request"),
        ),
    ];

    for (label, request) in cases {
        let response = send(router.clone(), request).await;
        assert_status(label, &game, &response, &sane);
        if response.status == StatusCode::OK {
            assert_move_list_body(label, &game, &response);
        }
    }
}

#[tokio::test]
async fn a_maximal_length_garbage_history_is_rejected_promptly() {
    let router = default_router();
    let mut rng = Rng::new(0x3F84_D5B5_B547_0917);
    // Exactly the cap: the length check passes, so the replay itself has to
    // be what stops this, and it has to stop fast.
    let body = rng.bytes(DEFAULT_MAX_HISTORY_MOVES * MOVE_BYTES);

    let started = Instant::now();
    let response = send(router.clone(), post_request("/replay-moves", body.clone())).await;
    let elapsed = started.elapsed();

    assert_status(
        "/replay-moves",
        &body,
        &response,
        &[StatusCode::BAD_REQUEST],
    );
    assert!(
        elapsed < Duration::from_secs(5),
        "a {}-move garbage history took {elapsed:?} to reject\n  payload: {}",
        DEFAULT_MAX_HISTORY_MOVES,
        hex(&body),
    );
}
