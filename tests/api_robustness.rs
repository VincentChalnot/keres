/// White king on e5, black king on f5, everything else empty, white to move —
/// a minimal board that passes `Board::validate`, so square 0 is the only
/// variable in the square-byte sweep.
fn two_king_payload(square_zero: u8) -> Vec<u8> {
    let mut payload = vec![0u8; GAME_BYTES];
    payload[0] = square_zero;
    payload[40] = 0b0111_1000; // White king (C=1, 111, 000).
    payload[41] = 0b0011_1000; // Black king (C=0, 111, 000).
    payload[BOARD_FLAGS] = 0b1000_0000; // White to move.
    payload
}

const BOARD_FLAGS: usize = GAME_BYTES - 2;
const BOARD_COUNTER: usize = GAME_BYTES - 1;

/// A router whose search cannot run away: the engine fuzz cases must not be
/// able to pin a blocking thread for a full minute if a random payload ever
/// does decode into a searchable position.
fn short_search_router() -> Router {
    api::router(ApiConfig {
        search_timeout: Duration::from_secs(5),
        search_queue_timeout: Duration::from_secs(1),
        ..ApiConfig::default()
    })
}

/// A fresh game plus a legal, non-`force_unstack` move for it: the canonical
/// 85-byte `/play` payload the truncation sweep chips away at.
async fn valid_play_payload() -> Vec<u8> {
    let game = new_game_bytes().await;
    let moves = post("/moves", game.clone()).await;
    assert_eq!(moves.status, StatusCode::OK);
    let potential = moves
        .u16s()
        .into_iter()
        .find(|raw| raw & 0x8000 == 0)
        .expect("the opening position has a move that does not force an unstack");
    let mut payload = game;
    payload.extend_from_slice(&move_bytes(potential_to_move(potential)));
    payload
}

/// A genuinely legal move history, built off-line with the library so the
/// history fuzzer has a corpus that survives past the first ply — random
/// bytes practically never do, and a replay that dies on move 0 exercises
/// none of the replay loop.
fn legal_history(rng: &mut Rng, plies: usize) -> Vec<u8> {
    let mut game = Game::new();
    let mut bytes = Vec::with_capacity(plies * MOVE_BYTES);
    for _ in 0..plies {
        let candidates: Vec<Move> = game
            .get_all_moves()
            .iter()
            .flat_map(|potential| potential.to_moves())
            .collect();
        if candidates.is_empty() {
            break;
        }
        let mv = candidates[rng.below(candidates.len())];
        if game.try_make(&mv).is_err() {
            break;
        }
        bytes.extend_from_slice(&mv.to_u16().to_le_bytes());
    }
    bytes
}

/// Status tally for a fuzz sweep.
///
/// "Never a 500" is trivially satisfied by a corpus that dies in the very
/// first length check, so each sweep also records what it actually provoked
/// and asserts that the interesting outcomes were reached — otherwise a
/// future change to the generator could silently turn these into no-ops.
#[derive(Debug, Default)]
struct Tally {
    total: usize,
    ok: usize,
    bad_request: usize,
    conflict: usize,
    too_large: usize,
}

impl Tally {
    fn record(&mut self, status: StatusCode) {
        self.total += 1;
        match status {
            StatusCode::OK => self.ok += 1,
            StatusCode::BAD_REQUEST => self.bad_request += 1,
            StatusCode::CONFLICT => self.conflict += 1,
            StatusCode::PAYLOAD_TOO_LARGE => self.too_large += 1,
            _ => {}
        }
    }

    #[track_caller]
    fn assert_reached(&self, route: &str, what: &str, count: usize, minimum: usize) {
        assert!(
            count >= minimum,
            "the {route} fuzz corpus only produced {count} {what} responses out of {} cases \
             (expected at least {minimum}) — the generator is no longer exercising that path",
            self.total,
        );
    }
}

