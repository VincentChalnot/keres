/// One history-fuzz body: random bytes of a whole number of moves, random
/// bytes of an arbitrary length (so odd lengths hit the multiple-of-2
/// check), a legal history, or a legal history with one byte corrupted —
/// the last of which is the only cheap way to reach a rejection *deep* in
/// the replay loop rather than on move 0.
fn history_body(rng: &mut Rng, case: usize) -> Vec<u8> {
    match case % 4 {
        0 => {
            let len = rng.below(MAX_FUZZ_LEN + 1);
            rng.bytes(len - (len % MOVE_BYTES))
        }
        1 => {
            let len = rng.below(MAX_FUZZ_LEN + 1);
            rng.bytes(len)
        }
        2 => {
            let plies = rng.below(13);
            legal_history(rng, plies)
        }
        _ => {
            let plies = 1 + rng.below(12);
            let mut body = legal_history(rng, plies);
            if !body.is_empty() {
                let index = rng.below(body.len());
                body[index] = rng.next_u8();
            }
            body
        }
    }
}

#[tokio::test]
async fn fuzzed_engine_board_payloads_never_produce_a_server_error() {
    let router = short_search_router();
    let mut rng = Rng::new(0x082E_FA98_EC4E_6C89);
    let allowed = [
        StatusCode::OK,
        StatusCode::BAD_REQUEST,
        StatusCode::CONFLICT,
        StatusCode::SERVICE_UNAVAILABLE,
    ];

    // An empty board is structurally valid but has no legal move: it reaches
    // the search (unlike every random payload, which dies in the decoder)
    // and must come back as a 409, not a 500.
    let empty_board = vec![0u8; GAME_BYTES];
    let response = send(
        router.clone(),
        post_request("/engine-move-board", empty_board.clone()),
    )
    .await;
    assert_status(
        "/engine-move-board",
        &empty_board,
        &response,
        &[StatusCode::CONFLICT],
    );

    for _ in 0..ENGINE_FUZZ_CASES {
        let body = rng.bytes(GAME_BYTES);
        let response = send(
            router.clone(),
            post_request("/engine-move-board", body.clone()),
        )
        .await;
        assert_status("/engine-move-board", &body, &response, &allowed);
        if response.status == StatusCode::OK {
            assert_move_body("/engine-move-board", &body, &response);
        }
    }
}

