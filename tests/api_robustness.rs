//! Hostile-input robustness for the binary HTTP API.
//!
//! The contract this file pins is the one `src/api.rs` opens with: *no byte
//! string a caller can send may reach a panicking code path*. Concretely,
//! for every payload exercised here the API must answer with a status that
//! blames the caller (`400`/`409`/`413`, plus `503` where a search can time
//! out) or succeed with a well-formed body — never `500`, never a dropped
//! connection, never a hang.
//!
//! Randomness is a deterministic xorshift64 seeded with fixed constants, so
//! a failure reproduces exactly on the next run and CI never goes flaky. No
//! fuzzing dependency is pulled in for that: the generator is ten lines.
//!
//! Every assertion names the offending payload in hex, because a fuzz
//! failure is worthless if you cannot replay the one body that caused it.

mod common;

use common::*;

