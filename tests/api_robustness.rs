#[tokio::test]
async fn every_move_bit_pattern_boundary_is_rejected_or_played_without_a_server_error() {
    let router = default_router();
    let game = new_game_bytes().await;
    let allowed = [
        StatusCode::OK,
        StatusCode::BAD_REQUEST,
        StatusCode::CONFLICT,
    ];

    // Both flag bits × every interesting square index: 0 and 80 are the ends
    // of the legal range, 81 is the first off-board index the 7-bit field can
    // hold and 127 is its maximum.
    for force_unstack in [0u16, 1] {
        for unstack in [0u16, 1] {
            for from in [0u16, 80, 81, 127] {
                for to in [0u16, 80, 81, 127] {
                    let raw = (force_unstack << 15) | (unstack << 14) | (to << 7) | from;
                    let mut body = game.clone();
                    body.extend_from_slice(&move_bytes(raw));
                    let response = send(router.clone(), post_request("/play", body.clone())).await;
                    assert_status("/play", &body, &response, &allowed);
                    if response.status == StatusCode::OK {
                        assert_game_body("/play", &body, &response);
                    }
                }
            }
        }
    }
}

