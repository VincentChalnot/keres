#[tokio::test]
async fn fuzzed_moves_payloads_are_rejected_or_answered_with_a_valid_move_list() {
    let router = default_router();
    let valid = new_game_bytes().await;
    let mut rng = Rng::new(0x243F_6A88_85A3_08D3);
    let allowed = [
        StatusCode::OK,
        StatusCode::BAD_REQUEST,
        StatusCode::PAYLOAD_TOO_LARGE,
    ];

    let mut tally = Tally::default();
    for case in 0..MOVES_FUZZ_CASES {
        let body = fuzz_body(&mut rng, case, GAME_BYTES, &valid);
        let response = send(router.clone(), post_request("/moves", body.clone())).await;
        assert_status("/moves", &body, &response, &allowed);
        if response.status == StatusCode::OK {
            assert_move_list_body("/moves", &body, &response);
        }
        tally.record(response.status);
    }

    tally.assert_reached("/moves", "200", tally.ok, 200);
    tally.assert_reached("/moves", "400", tally.bad_request, 200);
    tally.assert_reached("/moves", "413", tally.too_large, 200);
}

